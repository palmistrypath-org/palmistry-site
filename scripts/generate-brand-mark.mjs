/**
 * Generates src/components/BrandMark.astro — the Palmistry Path mark.
 *
 * The hand is built from measured geometry (finger axes and radii, thumb,
 * thenar, percussion) so the proportions are a hand's, not an icon's: middle
 * finger longest, ring above index, little finger short and splayed, thumb
 * angled out at about 30°. The wrist is left open so it reads as a drawing
 * rather than a glove. Inside: heart, head and life lines. A four-point star
 * hangs at the upper right.
 *
 *   node scripts/generate-brand-mark.mjs [preview.html]
 */
import { writeFileSync } from 'node:fs';

const f = (n) => Number(n.toFixed(2));
const P = (x, y) => ({ x: f(x), y: f(y) });
const sub = (a, b) => ({ x: a.x - b.x, y: a.y - b.y });
const add = (a, b) => ({ x: a.x + b.x, y: a.y + b.y });
const mul = (a, k) => ({ x: a.x * k, y: a.y * k });
const norm = (a) => {
	const l = Math.hypot(a.x, a.y);
	return { x: a.x / l, y: a.y / l };
};
const perp = (a) => ({ x: -a.y, y: a.x }); // for an upward axis this points +x (right)
const s = (p) => `${f(p.x)} ${f(p.y)}`;

// Finger capsules: base centre, tip centre, radius. Left to right.
const fingers = [
	{ name: 'index', base: P(31, 61), tip: P(27.5, 20), r: 6.2 },
	{ name: 'middle', base: P(45, 59), tip: P(45.5, 10.5), r: 6.4 },
	{ name: 'ring', base: P(59, 60), tip: P(61.5, 16), r: 6.1 },
	{ name: 'little', base: P(72, 64), tip: P(78.5, 32), r: 5.3 },
];
// Web heights between adjacent fingers.
const webs = [57.5, 56.5, 60.5];
const thumb = { base: P(25, 77), tip: P(7.5, 49.5), r: 6.3 };
// Fingers taper toward the tip.
const TAPER = 0.86;

function sides(c) {
	const d = norm(sub(c.tip, c.base));
	const n = perp(d);
	const rt = c.r * TAPER;
	const right = { a: add(c.base, mul(n, c.r)), b: add(c.tip, mul(n, rt)) };
	const left = { a: sub(c.base, mul(n, c.r)), b: sub(c.tip, mul(n, rt)) };
	return { d, n, left, right, rt };
}
const atY = (line, y) => {
	const t = (y - line.a.y) / (line.b.y - line.a.y);
	return { x: line.a.x + (line.b.x - line.a.x) * t, y };
};

const F = fingers.map(sides);
const T = sides(thumb);

let d = '';
// Start: wrist left, rising through the thenar into the thumb's outer edge.
const wristL = P(27, 113);
const thumbOuterBase = T.left.a;
d += `M ${s(wristL)} `;
d += `C ${s(P(24, 104))} ${s(P(14, 93))} ${s(thumbOuterBase)} `;
d += `L ${s(T.left.b)} `;
d += `A ${f(T.rt)} ${f(T.rt)} 0 0 1 ${s(T.right.b)} `;
const thumbWebY = 68;
const thumbInnerWeb = atY(T.right, thumbWebY);
d += `L ${s(thumbInnerWeb)} `;
const indexOuterWeb = atY(F[0].left, 62.5);
d += `C ${s(P(thumbInnerWeb.x + 1.5, thumbWebY - 2.5))} ${s(P(indexOuterWeb.x - 0.3, indexOuterWeb.y + 2.5))} ${s(indexOuterWeb)} `;
// Fingers
fingers.forEach((c, i) => {
	const S = F[i];
	d += `L ${s(S.left.b)} `;
	d += `A ${f(S.rt)} ${f(S.rt)} 0 0 1 ${s(S.right.b)} `;
	if (i < fingers.length - 1) {
		const wy = webs[i];
		const a = atY(S.right, wy);
		const b = atY(F[i + 1].left, wy);
		d += `L ${s(a)} `;
		d += `C ${s(P(a.x + 0.3, wy + 2.6))} ${s(P(b.x - 0.3, wy + 2.6))} ${s(b)} `;
	} else {
		const a = atY(S.right, 66);
		d += `L ${s(a)} `;
		// Percussion: the outer palm edge swells out and returns to the wrist.
		const wristR = P(75, 113);
		d += `C ${s(P(a.x + 6, 74))} ${s(P(84, 96))} ${s(wristR)}`;
	}
});
const HAND = d;

// Interior lines (heart, head, life), drawn finer.
const HEART = 'M 76 73 C 64 69 50 68 37 64';
const HEAD = 'M 27 71 C 40 74 55 79 68 86';
const LIFE = 'M 28 70 C 20 84 24 100 37 111';

// Four-point star.
function star(cx, cy, r, k = 0.24) {
	const q = f(r * k);
	return `M ${cx} ${cy - r} Q ${cx + q} ${cy - q} ${cx + r} ${cy} Q ${cx + q} ${cy + q} ${cx} ${cy + r} Q ${cx - q} ${cy + q} ${cx - r} ${cy} Q ${cx - q} ${cy - q} ${cx} ${cy - r} Z`;
}
const STAR = star(90, 22, 5);
const STAR_SMALL = star(12, 32, 2.4);

const VB = { x: 0, y: 2, w: 98, h: 114 };
const strokePx = (h) => (h <= 28 ? 1.15 : h <= 44 ? 1.4 : 1.6);

const astro = `---
/**
 * The Palmistry Path mark: an open hand drawn as one fine gold contour with
 * the heart, head and life lines inside and a four-point star at its shoulder.
 * The wrist is left open, so it reads as a drawing rather than a glove.
 *
 * Generated by scripts/generate-brand-mark.mjs. Edit the geometry there and
 * re-run; do not hand-edit the path data.
 *
 * Props: \`size\` is the rendered height in px. The stroke is set in px so the
 * mark keeps the same line quality at 20px and 60px. \`star\` toggles the star.
 */
interface Props {
	size?: number;
	class?: string;
	star?: boolean;
}
const { size = 24, class: className = '', star = true } = Astro.props;
const VB = { x: ${VB.x}, y: ${VB.y}, w: ${VB.w}, h: ${VB.h} };
const width = Math.round((size * VB.w) / VB.h);
const px = size <= 28 ? 1.15 : size <= 44 ? 1.4 : 1.6;
const sw = (px * VB.h) / size;
const fine = sw * 0.72;
---

<svg
	class={\`brand-mark \${className}\`.trim()}
	width={width}
	height={size}
	viewBox={\`\${VB.x} \${VB.y} \${VB.w} \${VB.h}\`}
	aria-hidden="true"
	fill="none"
	stroke="currentColor"
	stroke-linecap="round"
	stroke-linejoin="round"
>
	<path d="${HAND}" stroke-width={sw} />
	<g stroke-width={fine} opacity={size <= 28 ? 0.62 : 0.78}>
		<path d="${HEART}" />
		{size > 28 && <path d="${HEAD}" />}
		<path d="${LIFE}" />
	</g>
	{star && (
		<g fill="currentColor" stroke="none">
			<path d="${STAR}" />
			<path d="${STAR_SMALL}" opacity="0.6" />
		</g>
	)}
</svg>
`;
writeFileSync('src/components/BrandMark.astro', astro);

// Standalone preview for QA (not shipped).
const svgAt = (h, starOn = true) => {
	const sw = (strokePx(h) * VB.h) / h;
	const fine = sw * 0.72;
	const head = h > 28 ? `<path d="${HEAD}"/>` : '';
	const stars = starOn ? `<g fill="#c9a96e" stroke="none"><path d="${STAR}"/><path d="${STAR_SMALL}" opacity="0.6"/></g>` : '';
	return `<svg xmlns="http://www.w3.org/2000/svg" height="${h}" viewBox="${VB.x} ${VB.y} ${VB.w} ${VB.h}" fill="none" stroke="#c9a96e" stroke-linecap="round" stroke-linejoin="round"><path d="${HAND}" stroke-width="${f(sw)}"/><g stroke-width="${f(fine)}" opacity="${h <= 28 ? 0.62 : 0.78}"><path d="${HEART}"/>${head}<path d="${LIFE}"/></g>${stars}</svg>`;
};
const out = process.argv[2];
if (out) {
	const row = [22, 30, 56, 120, 260]
		.map((h) => `<div style="display:flex;flex-direction:column;align-items:center;gap:8px"><div style="height:${h}px">${svgAt(h)}</div><span>${h}px</span></div>`)
		.join('');
	const wordmark = `<div style="margin-top:40px;display:flex;gap:10px;align-items:center;color:#c9a96e;font:600 15px/1 Georgia,serif;letter-spacing:.16em">${svgAt(22)} PALMISTRY PATH</div>`;
	writeFileSync(out, `<body style="margin:0;background:#07050d;color:#8a7f6a;font:12px system-ui;padding:40px"><div style="display:flex;align-items:flex-end;gap:48px">${row}</div>${wordmark}</body>`);
}
